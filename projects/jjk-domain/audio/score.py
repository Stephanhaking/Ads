# audio/score.py — original score for the Domain Expansion "what if" video (~9:30). Night colours: a low pad and a slow
# celesta for the red dome closing, light marimba and pizzicato for the funny everyday blocks (the cat, the lift, the
# meeting), weight for the failing dome and the supermarket, a dense pulse for the station overload, open strings for the
# city-wide open domain, tension for the man who can't leave, a driving storm for the school, and a quiet close.
