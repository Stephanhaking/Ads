# audio/score.py — original score for the Saitama video (~10 min). Continuous bed, never silent. Light, deadpan-comic
# colours for the everyday scenes (pizzicato, marimba, a lazy "shrug" motif), a driving groove for the action, a lonely
# piano + pad for the boredom, a big swell for the meteor, and a quiet warm close. Original material only.
S.set_key("D minor")
shrug = Motif("1 3 2 . 1 5 4 .", ".5 .5 1 .5 .5 .5 1 .5")
hero = Motif("1 5 8 7 5 3", "1 .5 .5 1 .5 1.5")
lonely = Motif("5 4 3 . 2 1 .", "1 .5 1.5 .5 1 2 1")
W = lambda p, a=0: S.word(p, after=a)
cuts = [W("Sometime during the night"), W("First problem"), W("You need to know how strong"), W("On day five"), W("By day nine"),
        W("On day twelve"), W("On day seventeen"), W("After the crane"), W("On day thirty"), W("Word gets around"), W("By day sixty"),
        W("This is the part nobody"), W("One night, just to feel"), W("And then, on day"), W("So you do what Saitama")]
t = [0] + cuts + [S.duration]

A = S.section("open", t[0], t[1], bpm=96, chords="i:2 bVI:2 bVII:2 i:2")
A.pad("pad_warm", 3, 24, "open"); A.ticks("stick", step=0.5, vel=16); A.pulse("synth_bass", octave=2, vel=32, step=1)
S.hit(W("goes through the nightstand"), "impact", vel=84); S.hit(W("Not a single hair"), "pluck", vel=66)
B = S.section("reveal", t[1], t[2], bpm=104, chords="i:2 bVI:2 bIII:2 bVII:2")
