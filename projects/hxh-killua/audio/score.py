J.strings("tremolo", 3, 30, swell=0.6); J.pulse("synth_bass", octave=2, vel=34, step=0.5); J.pad("pad_space", 3, 22, "open")
S.hit(W("The wheel moves"), "boom", vel=84)
K = S.section("day41", t[10], t[11], bpm=74, key="G major", chords="vi:2 IV:2 I:2 V:2")
K.motif(hook, "piano", every=4, octave=4, vel=28); K.pad("pad_warm", 3, 24, "open", swell=0.3)
