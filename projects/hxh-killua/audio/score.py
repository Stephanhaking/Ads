# audio/score.py — original score for the Killua "what if" video (~7 min). Continuous bed, never silent. Electric and
# light: a fast staccato pulse for the power, a glassy arp for the spark, a drone for the storm, a bright run for the
# speed scenes, tension for the world noticing, a big lift at the Ferris wheel, a quiet close. Original material only.
S.set_key("E minor")
zap = Motif("1 . 5 1 . 5 8 .", ".25 .25 .25 .25 .25 .25 .25 .25")
hook = Motif("5 6 5 3 2 3 1 .", ".5 .5 .5 .5 .5 .5 1 .5")
W = lambda p, a=0: S.word(p, after=a)
cuts = [W("In the story, that energy"), W("On day three"), W("On day six"), W("On day ten"), W("The second half"), W("On day twenty-two"),
        W("On day twenty-six"), W("In the story, Godspeed"), W("On day forty"), W("The next morning"), W("So if you woke")]
t = [0] + cuts + [S.duration]
A = S.section("open", t[0], t[1], bpm=90, chords="i:2 bVI:2 iv:2 V:2")
A.pad("pad_glass", 3, 22, "open"); A.ticks("stick", step=0.5, vel=14); A.strings("tremolo", 3, 18, swell=0.4)
S.hit(W("There's a crack"), "boom", vel=80); S.hit(W("The lights come back"), "impact", vel=64)
B = S.section("day1", t[1], t[2], bpm=96, key="G major", chords="I:2 vi:2 IV:2 V:2")
B.arp("celesta", "1 5 8 5", step=0.5, octave=4, vel=16); B.pad("pad_warm", 3, 18, "open")
C = S.section("day3", t[2], t[3], bpm=92, chords="i:2 iv:2 bVI:2 V:2")
C.pad("pad_space", 3, 20, "open"); C.motif(hook, "pizz", every=4, octave=4, vel=22)
S.hit(W("and it hurts"), "impact", vel=60)
D = S.section("day6", t[3], t[4], bpm=84, chords="i:2 bVI:2 bIII:2 bVII:2")
D.pad("pad_glass", 3, 22, "open"); D.arp("celesta", "1 3 5 8", step=0.5, octave=4, vel=14)
E = S.section("day10", t[4], t[5], bpm=104, key="G major", chords="I:1 V:1 vi:1 IV:1")
E.ostinato(zap, "marimba", octave=4, vel=24); E.pulse("synth_bass", octave=2, vel=30, step=0.5); E.pad("pad_warm", 3, 18, "open")
S.hit(W("You catch it"), "impact", vel=70)
F = S.section("day15", t[5], t[6], bpm=120, chords="i:1 bVI:1 bVII:1 V:1")
F.drums({"kick": "x...x...", "snare": "....x...", "hat": "xxxxxxxx"}, "kit", step=0.25, vel=30); F.pulse("synth_bass", octave=2, vel=34, step=0.5); F.ostinato(zap, "marimba", octave=4, vel=22)
S.hit(W("straight into the fence"), "boom", vel=76)
G = S.section("day22", t[6], t[7], bpm=108, chords="i:2 iv:2 i:2 V:2")
G.drums({"kick": "x.....x.", "snare": "....x...", "hat": "x.x.x.x."}, "kit", step=0.25, vel=26); G.pulse("synth_bass", octave=2, vel=32, step=0.5); G.strings("strings", 3, 22, swell=0.4)
H = S.section("day26", t[7], t[8], bpm=80, chords="i:2 bVI:2 iv:2 V:2")
H.pad("pad_space", 3, 22, "open"); H.motif(hook, "piano", every=4, octave=4, vel=24)
