# audio/score.py — original score for the Star Platinum "what if" video (~6:47). Continuous bed, never silent except a
# held-breath hush during the time stop. A punchy pulse for the Stand, a bright run in the supermarket, heavy hits in the
# gym and the barrage, a thinking pad at the whiteboard, tension down the hill, a quiet close that mirrors the opening.
S.set_key("D minor")
punchm = Motif("1 . 1 5 . 1 8 .", ".25 .25 .25 .25 .25 .25 .25 .25")
hook = Motif("5 6 5 3 2 3 1 .", ".5 .5 .5 .5 .5 .5 1 .5")
W = lambda p, a=0: S.word(p, after=a)
cuts = [W("Nobody else can see it"), W("At noon you go"), W("That evening you take"), W("Every fan knows"), W("At night your keys"),
        W("A boy in the park"), W("Fans love the scenes"), W("By day thirty"), W("On day forty"), W("The world goes silent"),
        W("And the world starts again"), W("The next morning you can't"), W("The next morning, seven twelve")]
t = [0] + cuts + [S.duration]
A = S.section("open", t[0], t[1], bpm=84, chords="i:2 bVI:2 iv:2 V:2")
A.pad("pad_glass", 3, 22, "open"); A.ticks("stick", step=0.5, vel=12); A.strings("tremolo", 3, 16, swell=0.4)
S.hit(W("Something else does"), "impact", vel=70); S.hit(W("You've woken up with Star"), "boom", vel=80); S.hit(W("it's going to cost"), "impact", vel=60)
B = S.section("am740", t[1], t[2], bpm=96, key="F major", chords="I:2 vi:2 IV:2 V:2")
B.arp("celesta", "1 5 8 5", step=0.5, octave=4, vel=16); B.pad("pad_warm", 3, 18, "open")
C = S.section("noon", t[2], t[3], bpm=112, key="F major", chords="I:1 V:1 vi:1 IV:1")
C.ostinato(punchm, "marimba", octave=4, vel=24); C.pulse("synth_bass", octave=2, vel=30, step=0.5); C.pad("pad_warm", 3, 16, "open")
S.hit(W("and it starts to fall"), "impact", vel=66); S.hit(W("catches all of it"), "boom", vel=78)
D = S.section("gym", t[3], t[4], bpm=100, chords="i:2 iv:2 bVI:2 V:2")
D.drums({"kick": "x...x...", "snare": "....x...", "hat": "x.x.x.x."}, "kit", step=0.25, vel=26); D.pulse("synth_bass", octave=2, vel=32, step=0.5); D.strings("strings", 3, 20, swell=0.3)
S.hit(W("picks it up with one hand"), "boom", vel=80); S.hit(W("The bar bends"), "impact", vel=70)
E = S.section("day3", t[4], t[5], bpm=128, chords="i:1 bVI:1 bVII:1 V:1")
E.drums({"kick": "x.x.x.x.", "snare": "....x..x", "hat": "xxxxxxxx"}, "kit", step=0.25, vel=32); E.pulse("synth_bass", octave=2, vel=36, step=0.5); E.ostinato(punchm, "marimba", octave=4, vel=24)
S.hit(W("ORA"), "boom", vel=86); S.hit(W("Then it splits"), "boom", vel=80)
F = S.section("day6", t[5], t[6], bpm=80, chords="i:2 bVI:2 bIII:2 bVII:2")
F.pad("pad_space", 3, 22, "open"); F.arp("celesta", "1 3 5 8", step=0.5, octave=4, vel=14)
G = S.section("day10", t[6], t[7], bpm=104, key="F major", chords="I:1 V:1 vi:1 IV:1")
G.ostinato(punchm, "marimba", octave=4, vel=22); G.pad("pad_warm", 3, 18, "open"); G.pulse("synth_bass", octave=2, vel=28, step=0.5)
H = S.section("day15", t[7], t[8], bpm=78, chords="i:2 bVI:2 iv:2 V:2")
H.pad("pad_glass", 3, 22, "open"); H.motif(hook, "piano", every=4, octave=4, vel=22); H.ticks("stick", step=1, vel=12)
S.hit(W("Jotaro learns to stop time"), "impact", vel=64)
I = S.section("day30", t[8], t[9], bpm=88, chords="i:2 bII:2 i:2 V:2")
I.pad("pad_space", 3, 20, "open"); I.ticks("stick", step=0.5, vel=14); I.motif(hook, "pizz", every=4, octave=4, vel=20)
J = S.section("day40", t[9], t[10], bpm=120, chords="i:1 bVI:1 bIII:1 bVII:1")
J.strings("tremolo", 3, 30, swell=0.6); J.pulse("synth_bass", octave=2, vel=36, step=0.5); J.drums({"kick": "x...x...", "snare": "....x...", "hat": "x.x.x.x."}, "kit", step=0.25, vel=26)
S.hit(W("You hold your breath"), "boom", vel=82)
Z = S.section("stop", t[10], t[11], bpm=60, chords="i:4 bVI:4")
Z.pad("pad_glass", 3, 14, "open")
S.hit(W("And the world starts again"), "boom", vel=84)
R = S.section("after", t[11], t[12], bpm=96, key="F major", chords="I:2 vi:2 IV:2 V:2")
R.pad("pad_warm", 3, 22, "open", swell=0.3); R.strings("strings", 3, 20, swell=0.4)
K2 = S.section("day41", t[12], t[13], bpm=72, key="F major", chords="vi:2 IV:2 I:2 V:2")
K2.motif(hook, "piano", every=4, octave=4, vel=26); K2.pad("pad_warm", 3, 22, "open", swell=0.3)
L = S.section("ending", t[13], t[14], bpm=84, chords="i:2 bVI:2 iv:2 V:2")
L.pad("pad_glass", 3, 22, "open", swell=0.4); L.arp("celesta", "1 5 8 5", step=0.5, octave=4, vel=16)
S.hit(W("And something catches it"), "impact", vel=66)
