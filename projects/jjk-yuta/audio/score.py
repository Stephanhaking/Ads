# audio/score.py — original score for the Yuta / Copy "what if" video (~9:29). Night colours: a soft pad and a music-box
# celesta for the pale figure and the ring (sad and protective, never threatening), light marimba for the copied skills,
# a guitar-like pluck for the busker, weight for the climbing fall, tension for the ring coming off and the pavement,
# a driving pulse for the flooded tunnel, and a quiet close that mirrors the 11:47 opening.
